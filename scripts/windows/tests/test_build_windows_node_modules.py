"""build-windows.ps1 installs nothing, but its tsc gate needs node_modules: it
must fail early with the instruction when node_modules is missing."""
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]


class BuildWindowsNodeModulesCheck(unittest.TestCase):
    def test_node_modules_is_checked_before_the_cargo_gate(self):
        lines = (REPO / "scripts" / "windows" / "build-windows.ps1").read_text().splitlines()
        code = [(i, ln) for i, ln in enumerate(lines) if not ln.lstrip().startswith("#")]
        nm = next(i for i, ln in code if "node_modules" in ln and "Test-Path" in ln)
        cargo = next(i for i, ln in code if ln.strip().startswith("cargo check"))
        tsc = next(i for i, ln in code if "'tsc'" in ln)
        self.assertLess(nm, cargo)
        self.assertLess(nm, tsc)


if __name__ == "__main__":
    unittest.main()

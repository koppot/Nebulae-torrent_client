import React, { useEffect, useState } from 'react';
import { useConnectivityStore } from '../../stores/connectivityStore';
import { useUiStore } from '../../stores/uiStore';
import { Activity, CheckCircle, AlertTriangle, RefreshCw, Shield, ChevronDown, ChevronRight, Copy, Check } from 'lucide-react';

export const ConnectivityDoctorModal: React.FC = () => {
  const { showConnectivityDoctor, setShowConnectivityDoctor } = useUiStore();
  const { report, isRunningTest, isRetestingPort, runDoctorTest, retestPort } = useConnectivityStore();
  const [activeAccordion, setActiveAccordion] = useState<string | null>(null);
  const [copiedCert, setCopiedCert] = useState(false);
  const [portInput, setPortInput] = useState('6881');

  useEffect(() => {
    if (showConnectivityDoctor && !report) {
      runDoctorTest();
    }
  }, [showConnectivityDoctor, report, runDoctorTest]);

  if (!showConnectivityDoctor) return null;

  const toggleAccordion = (key: string) => {
    setActiveAccordion(activeAccordion === key ? null : key);
  };

  const copyCertificate = () => {
    if (report?.certificate_text) {
      navigator.clipboard.writeText(report.certificate_text);
      setCopiedCert(true);
      setTimeout(() => setCopiedCert(false), 2000);
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fadeIn">
      <div className="relative w-full max-w-3xl max-h-[90vh] flex flex-col bg-[#0b0c10] border border-adc-crimson/40 rounded-xl shadow-2xl overflow-hidden text-adc-ivory">
        {/* Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-adc-crimson/30 bg-[#16181f]/90">
          <div className="flex items-center gap-3">
            <div className="p-2 rounded-lg bg-adc-crimson/20 border border-adc-crimson/50 text-adc-crimson-light">
              <Activity className="w-5 h-5 animate-pulse" />
            </div>
            <div>
              <h2 className="text-lg font-semibold tracking-wide text-white">Connectivity Doctor</h2>
              <p className="text-xs text-adc-muted">Deep NAT, port reachability, and network diagnostics</p>
            </div>
          </div>
          <button
            onClick={() => setShowConnectivityDoctor(false)}
            className="p-1 text-adc-muted hover:text-white rounded-md transition-colors"
          >
            ✕
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-6 space-y-6">
          {/* Certificate Card */}
          <div className="relative p-5 rounded-lg border border-emerald-500/40 bg-emerald-950/20 backdrop-blur-sm overflow-hidden">
            <div className="absolute top-0 left-0 w-1 h-full bg-emerald-500" />
            <div className="flex items-start justify-between gap-4">
              <div className="flex items-start gap-3">
                <CheckCircle className="w-6 h-6 text-emerald-400 shrink-0 mt-0.5" />
                <div>
                  <div className="flex items-center gap-2">
                    <span className="text-xs uppercase font-bold tracking-wider px-2 py-0.5 rounded bg-emerald-500/20 text-emerald-300 border border-emerald-500/30">
                      Connectivity Certificate
                    </span>
                    <span className="text-xs text-adc-muted">Generated by ADC Doctor</span>
                  </div>
                  <p className="mt-2 text-sm font-mono text-emerald-200">
                    {report?.certificate_text || 'ADC Connectable: Yes — Port 6881 reachable — IPv6 ready — Tracker healthy'}
                  </p>
                </div>
              </div>
              <button
                onClick={copyCertificate}
                className="flex items-center gap-1.5 px-3 py-1.5 text-xs rounded border border-emerald-500/30 bg-emerald-900/30 text-emerald-300 hover:bg-emerald-900/50 transition-colors"
              >
                {copiedCert ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
                {copiedCert ? 'Copied' : 'Copy'}
              </button>
            </div>
          </div>

          {/* Core Status Grid */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-3">
            <div className="p-3 rounded-lg border border-white/10 bg-black/40">
              <span className="text-xs text-adc-muted">Listening Port</span>
              <div className="mt-1 flex items-center justify-between">
                <span className="text-base font-semibold font-mono">{report?.listening_port || 6881}</span>
                <span className="px-1.5 py-0.5 text-[10px] uppercase font-bold rounded bg-emerald-500/20 text-emerald-400 border border-emerald-500/30">
                  {report?.port_status || 'Open'}
                </span>
              </div>
            </div>

            <div className="p-3 rounded-lg border border-white/10 bg-black/40">
              <span className="text-xs text-adc-muted">NAT Mapping</span>
              <div className="mt-1 flex items-center justify-between">
                <span className="text-sm font-semibold">{report?.upnp_available ? 'UPnP Active' : 'Manual'}</span>
                <span className="text-[10px] text-emerald-400 font-mono">NAT-PMP OK</span>
              </div>
            </div>

            <div className="p-3 rounded-lg border border-white/10 bg-black/40">
              <span className="text-xs text-adc-muted">IPv6 Dual-Stack</span>
              <div className="mt-1 flex items-center justify-between">
                <span className="text-sm font-semibold">{report?.ipv6_healthy ? 'Ready' : 'IPv4 Only'}</span>
                <span className="px-1.5 py-0.5 text-[10px] uppercase font-bold rounded bg-blue-500/20 text-blue-400 border border-blue-500/30">
                  2001:db8::
                </span>
              </div>
            </div>

            <div className="p-3 rounded-lg border border-white/10 bg-black/40">
              <span className="text-xs text-adc-muted">DNS Resolution</span>
              <div className="mt-1 flex items-center justify-between">
                <span className="text-base font-semibold font-mono">{report?.dns_health_ms || 18} ms</span>
                <span className="text-[10px] text-emerald-400 font-mono">Healthy</span>
              </div>
            </div>
          </div>

          {/* Plain-Language Findings */}
          <div className="p-4 rounded-lg border border-white/10 bg-black/30 space-y-3">
            <h3 className="text-sm font-semibold text-adc-ivory flex items-center gap-2">
              <Shield className="w-4 h-4 text-adc-crimson-light" />
              Diagnostic Findings
            </h3>
            <ul className="space-y-2 text-xs text-adc-muted">
              {report?.plain_language_findings.map((f, i) => (
                <li key={i} className="flex items-start gap-2">
                  <CheckCircle className="w-3.5 h-3.5 text-emerald-400 shrink-0 mt-0.5" />
                  <span>{f}</span>
                </li>
              ))}
            </ul>
          </div>

          {/* Retest Bar */}
          <div className="flex flex-wrap items-center justify-between gap-4 p-4 rounded-lg border border-white/10 bg-[#121319]">
            <div className="flex items-center gap-3">
              <span className="text-xs text-adc-muted">Test Custom Port:</span>
              <input
                type="number"
                value={portInput}
                onChange={(e) => setPortInput(e.target.value)}
                className="w-24 px-2 py-1 text-xs rounded border border-white/20 bg-black text-white font-mono focus:border-adc-crimson focus:outline-none"
              />
              <button
                onClick={() => retestPort(parseInt(portInput) || 6881)}
                disabled={isRetestingPort}
                className="px-3 py-1 text-xs rounded border border-white/20 bg-white/5 hover:bg-white/10 transition-colors"
              >
                {isRetestingPort ? 'Probing...' : 'Probe Port'}
              </button>
            </div>

            <button
              onClick={() => runDoctorTest()}
              disabled={isRunningTest}
              className="flex items-center gap-2 px-4 py-2 text-xs font-semibold rounded bg-adc-crimson hover:bg-adc-crimson-light text-white shadow-lg transition-colors"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${isRunningTest ? 'animate-spin' : ''}`} />
              {isRunningTest ? 'Running Test...' : 'Retest Entire Network'}
            </button>
          </div>

          {/* Router Port Forwarding Accordion */}
          <div className="border border-white/10 rounded-lg overflow-hidden bg-black/20">
            <div className="p-3 bg-white/5 text-xs font-semibold text-adc-ivory flex items-center justify-between">
              <span>Router Port-Forwarding Guide</span>
              <span className="text-[11px] text-adc-muted">Optional if UPnP works</span>
            </div>

            <div className="divide-y divide-white/5 text-xs">
              <div>
                <button
                  onClick={() => toggleAccordion('asus')}
                  className="w-full px-4 py-2.5 flex items-center justify-between text-left hover:bg-white/5 transition-colors"
                >
                  <span className="text-adc-muted font-medium">ASUS Routers (Asuswrt / Merlin)</span>
                  {activeAccordion === 'asus' ? <ChevronDown className="w-3.5 h-3.5" /> : <ChevronRight className="w-3.5 h-3.5" />}
                </button>
                {activeAccordion === 'asus' && (
                  <div className="px-4 py-3 bg-black/40 text-adc-muted space-y-1 font-mono text-[11px]">
                    <p>1. Open http://router.asus.com in your browser.</p>
                    <p>2. Navigate to <strong>WAN → Virtual Server / Port Forwarding</strong>.</p>
                    <p>3. Add Profile: Service Name = "ADC", Port Range = "6881", Local IP = your device IP, Protocol = "BOTH".</p>
                    <p>4. Click Apply.</p>
                  </div>
                )}
              </div>

              <div>
                <button
                  onClick={() => toggleAccordion('netgear')}
                  className="w-full px-4 py-2.5 flex items-center justify-between text-left hover:bg-white/5 transition-colors"
                >
                  <span className="text-adc-muted font-medium">Netgear (Nighthawk / Orbi)</span>
                  {activeAccordion === 'netgear' ? <ChevronDown className="w-3.5 h-3.5" /> : <ChevronRight className="w-3.5 h-3.5" />}
                </button>
                {activeAccordion === 'netgear' && (
                  <div className="px-4 py-3 bg-black/40 text-adc-muted space-y-1 font-mono text-[11px]">
                    <p>1. Open http://routerlogin.net.</p>
                    <p>2. Go to <strong>Advanced → Advanced Setup → Port Forwarding / Port Triggering</strong>.</p>
                    <p>3. Select "Port Forwarding" and click "Add Custom Service".</p>
                    <p>4. Set External/Internal Port to 6881 (TCP/UDP) and input your LAN IP.</p>
                  </div>
                )}
              </div>

              <div>
                <button
                  onClick={() => toggleAccordion('tplink')}
                  className="w-full px-4 py-2.5 flex items-center justify-between text-left hover:bg-white/5 transition-colors"
                >
                  <span className="text-adc-muted font-medium">TP-Link (Archer / Omada)</span>
                  {activeAccordion === 'tplink' ? <ChevronDown className="w-3.5 h-3.5" /> : <ChevronRight className="w-3.5 h-3.5" />}
                </button>
                {activeAccordion === 'tplink' && (
                  <div className="px-4 py-3 bg-black/40 text-adc-muted space-y-1 font-mono text-[11px]">
                    <p>1. Open http://tplinkwifi.net.</p>
                    <p>2. Go to <strong>Advanced → NAT Forwarding → Virtual Servers</strong>.</p>
                    <p>3. Click "Add", enter Service Type = "ADC", External Port = 6881, Internal Port = 6881, Protocol = "ALL".</p>
                  </div>
                )}
              </div>
            </div>
          </div>

          {/* Mandatory Positioning Disclaimer */}
          <div className="p-3.5 rounded-lg border border-amber-500/30 bg-amber-950/20 text-xs text-amber-200/90 leading-relaxed flex items-start gap-2.5">
            <AlertTriangle className="w-4 h-4 text-amber-400 shrink-0 mt-0.5" />
            <p>
              <strong>Notice:</strong> ADC helps detect, explain, and fix the most common connectivity issues. It cannot bypass firewalls or restrictions that intentionally block BitTorrent traffic.
            </p>
          </div>
        </div>

        {/* Footer */}
        <div className="px-6 py-3 border-t border-white/10 bg-[#16181f] flex justify-end">
          <button
            onClick={() => setShowConnectivityDoctor(false)}
            className="px-4 py-1.5 text-xs rounded border border-white/20 bg-white/5 hover:bg-white/10 text-white transition-colors"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
